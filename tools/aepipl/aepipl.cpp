// Build step for the After Effects plugin: writes the PiPL resource source
// (one PiPL per effect, all in one plugin file) and the matching exported
// entry points, from the same Registry the plugin is built from.
// usage: aepipl OUT.r OUT_ENTRIES.cpp
#include <cstdio>
#include <fstream>

#include "ae/AeFlags.h"

using namespace prisma;
using namespace prisma::ae;

int main(int argc, char** argv) {
    if (argc != 3) {
        fprintf(stderr, "usage: aepipl OUT.r OUT_ENTRIES.cpp\n");
        return 2;
    }
    std::ofstream r(argv[1]), c(argv[2]);
    r << "// Generated by tools/aepipl. Do not edit.\n"
         "#include \"AEConfig.h\"\n"
         "#include \"AE_EffectVers.h\"\n"
         "#ifndef AE_OS_WIN\n"
         "  #include \"AE_General.r\"\n"
         "#endif\n";
    c << "// Generated by tools/aepipl. Do not edit.\n#include \"ae/AeEntry.h\"\n\n";
    int id = 16000;
    for (const auto& e : Registry::instance().effects()) {
        const EffectInfo& i = e->info();
        std::string entry = entryName(i);
        r << "\nresource 'PiPL' (" << id++ << ") {\n  {\n"
          << "    Kind { AEEffect },\n"
          << "    Name { \"" << i.label << "\" },\n"
          << "    Category { \"" << category(i) << "\" },\n"
          << "#ifdef AE_OS_WIN\n"
          << "  #if defined(AE_PROC_ARM64)\n"
          << "    CodeWinARM64 { \"" << entry << "\" },\n"
          << "  #else\n"
          << "    CodeWin64X86 { \"" << entry << "\" },\n"
          << "  #endif\n"
          << "#else\n"
          << "    CodeMacIntel64 { \"" << entry << "\" },\n"
          << "    CodeMacARM64 { \"" << entry << "\" },\n"
          << "#endif\n"
          << "    AE_PiPL_Version { 2, 0 },\n"
          << "    AE_Effect_Spec_Version { PF_PLUG_IN_VERSION, PF_PLUG_IN_SUBVERS },\n"
          << "    AE_Effect_Version { " << effectVersion(i.versionMajor, i.versionMinor) << " },\n"
          << "    AE_Effect_Info_Flags { 0 },\n"
          << "    AE_Effect_Global_OutFlags { " << kOutFlags << " },\n"
          << "    AE_Effect_Global_OutFlags_2 { " << kOutFlags2 << " },\n"
          << "    AE_Effect_Match_Name { \"" << matchName(i) << "\" },\n"
          << "    AE_Reserved_Info { 0 },\n"
          << "    AE_Effect_Support_URL { \"https://github.com/emivalc/prisma-fx\" }\n"
          << "  }\n};\n";
        c << "PRISMA_AE_ENTRY(" << entry << ", \"" << i.id << "\")\n";
    }
    return r && c ? 0 : 1;
}
